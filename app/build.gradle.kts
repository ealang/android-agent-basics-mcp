// The debug keystore lives outside the repo (path comes from local.properties),
// so a rebuilt container signs with the same key and the APK still installs
// over the copy already on the phone.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

/**
 * Build-time settings, from local.properties (gitignored) or the environment,
 * so a release machine with no checked-out properties file can supply them too.
 */
fun buildSetting(name: String): String? =
    (localProps[name]?.toString() ?: System.getenv(name))?.trim()?.ifEmpty { null }

// The Telegram application credentials, baked in rather than typed by the user
// (2026-09-19). They identify the *application*, not the account — every
// install of a Telegram client ships the same pair, and the official clients'
// values are published — so asking each user to register at my.telegram.org
// was work with nothing to show for it. Not secret either: anything in an APK
// decompiles in seconds. Gitignored only because they are a personal
// registration that Telegram can revoke if abused.
//
// Absent, the build still succeeds and the app says it has no credentials:
// a clone without a pair must stay buildable.
val telegramApiId = buildSetting("TELEGRAM_API_ID")?.toIntOrNull() ?: 0
val telegramApiHash = buildSetting("TELEGRAM_API_HASH").orEmpty()

// Which ABIs a *debug* APK carries. TDLib is ~25 MB per architecture, so an
// unfiltered debug build is 107 MB of which one architecture is usable on any
// given phone; naming the one you install onto cuts it to about 30 MB.
// Comma-separated, e.g. DEV_ABIS=arm64-v8a in local.properties.
//
// Debug only, on purpose: a release build must never be silently narrowed by a
// line someone left in their properties file months ago. Release packaging is
// a separate, deliberate decision (App Bundle or ABI splits) — see
// docs/initial-release.md §11.
val devAbis = buildSetting("DEV_ABIS")
    ?.split(",")
    ?.map { it.trim() }
    ?.filter { it.isNotEmpty() }
    .orEmpty()

